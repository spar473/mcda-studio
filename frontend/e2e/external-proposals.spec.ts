import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import type { Project, ProposalCompilation } from "../src/api/types";
import { openTab, readJson, REPO, storedFile } from "./helpers";

for (const domain of ["screening", "supplier"] as const) {
  test(`${domain} proposals: explicit bulk review, correction, rejection, disagreement and historical bundle`, async ({ page, request }, testInfo) => {
    const base = resolve(REPO, "examples/external_proposals");
    const project = readJson(resolve(base, `${domain}-project.json`)) as Project;
    const imported = await request.post("/api/projects/import", { data: project });
    expect([201, 409]).toContain(imported.status());
    const original = await storedFile(request, project.id);
    await page.goto(`/#/p/${project.id}`); await openTab(page, "Evidence");
    await page.getByText("External proposals", { exact: true }).click();
    const panel = page.getByLabel("External proposals", { exact: true });
    await panel.getByLabel("Import proposal file").setInputFiles(resolve(base, `${domain}-intake.json`));
    await expect(panel.getByText(/7 matching proposals/)).toBeVisible();
    await expect(panel.getByText(/0 explicitly selected for bulk review/)).toBeVisible();
    await panel.getByRole("combobox", { name: "Compare proposals with", exact: true }).selectOption("human");
    await panel.getByRole("combobox", { name: "Proposal agreement", exact: true }).selectOption("disagreement");
    await expect(panel.getByLabel("Select proposal cell_a_first", { exact: true })).toBeVisible();
    await panel.getByRole("button", { name: "Compare cell cell_a_first", exact: true }).click();
    await expect(panel.getByRole("region", { name: "Proposal cell comparison" })).toContainText("human:human_a");
    await panel.getByRole("combobox", { name: "Proposal agreement", exact: true }).selectOption("");
    await panel.getByLabel("Select proposal readiness_b", { exact: true }).check();
    await panel.getByLabel("Select proposal tag_b", { exact: true }).check();
    await panel.getByLabel("Proposal reviewer", { exact: true }).fill("Illustrative reviewer");
    await expect(panel.getByRole("combobox", { name: "Proposal review decision", exact: true })).toHaveValue("");
    await panel.getByRole("combobox", { name: "Proposal review decision", exact: true }).selectOption("accepted");
    await panel.getByLabel("Proposal review note", { exact: true }).fill("Reviewed invented sources");
    await panel.getByRole("button", { name: "Use each selected proposal's sole cited source" }).click();
    await panel.getByRole("button", { name: "Preview selected proposal reviews" }).click();
    const confirmation = panel.getByRole("region", { name: "Proposal review confirmation" });
    await expect(confirmation.getByRole("listitem")).toHaveCount(2);
    await expect(confirmation).toContainText("readiness_b"); await expect(confirmation).toContainText("tag_b");
    await panel.getByRole("button", { name: "Confirm listed proposal reviews" }).click();
    await expect(panel.getByText("Proposal review history (2 events)", { exact: true })).toBeVisible();
    // Correct one proposal while retaining the original machine payload and original disagreement.
    await panel.getByRole("button", { name: "Review proposal cell_a_first", exact: true }).click();
    await panel.getByRole("combobox", { name: "Proposal review decision", exact: true }).selectOption("corrected");
    await panel.getByLabel("Corrected proposal payload (JSON)").fill(JSON.stringify({ kind: "categorical_cell", value: domain === "screening" ? "hardware" : "medium", unit: null }));
    await panel.getByRole("combobox", { name: "Primary source for cell_a_first", exact: true }).selectOption("brief_a");
    await panel.getByRole("button", { name: "Preview selected proposal reviews" }).click();
    await panel.getByRole("button", { name: "Confirm listed proposal reviews" }).click();
    await expect(panel.getByText("Proposal review history (3 events)", { exact: true })).toBeVisible();
    await panel.getByRole("button", { name: "Review proposal numeric_b", exact: true }).click();
    await panel.getByRole("combobox", { name: "Proposal review decision", exact: true }).selectOption("rejected");
    await panel.getByRole("button", { name: "Preview selected proposal reviews" }).click();
    await panel.getByRole("button", { name: "Confirm listed proposal reviews" }).click();
    await expect(panel.getByText("Proposal review history (4 events)", { exact: true })).toBeVisible();
    await panel.getByLabel("I reviewed every proposal measurement change and retained annotation").check();
    await panel.getByRole("button", { name: "Compile reviewed proposal copy", exact: true }).click();
    const complete = panel.getByRole("region", { name: "Proposal compilation bundle" });
    await expect(complete).toBeVisible();
    const download = page.waitForEvent("download");
    await complete.getByRole("button", { name: "Export proposal compilation bundle", exact: true }).click();
    const file = await (await download).path(); if (!file) throw Error("Missing downloaded bundle");
    const bundle = JSON.parse(readFileSync(file, "utf8")) as ProposalCompilation;
    expect(bundle.workspace.intake.proposals).toHaveLength(7);
    expect(bundle.workspace.reviews.map(e => e.review.status)).toEqual(["accepted", "accepted", "corrected", "rejected"]);
    expect(bundle.workspace.reviews[0]?.review.reviewed_at).toBe(bundle.workspace.reviews[1]?.review.reviewed_at);
    expect(bundle.annotations.map(a => a.proposal_id)).toEqual(["tag_b"]);
    const untouched = bundle.workspace.intake.proposals.find(p => p.id === "cell_a_first");
    expect(untouched?.payload.kind === "categorical_cell" && untouched.payload.value).toBe(domain === "screening" ? "software" : "high");
    expect((await storedFile(request, project.id)).equals(original)).toBe(true);
    const verified = await request.post("/api/proposals/verify", { data: bundle });
    expect(verified.status()).toBe(200); expect(await verified.json()).toEqual(bundle);
    await page.screenshot({ path: testInfo.outputPath("proposal-review.png") });
    await openTab(page, "Open Questions");
    await expect(page.getByRole("region", { name: "Open Questions", exact: true })).toContainText("Which differing proposal is supported?");
    await openTab(page, "Evidence");
    await panel.getByLabel("Open proposal compilation", { exact: true }).setInputFiles(file);
    await expect(complete).toContainText("Verified historical compilation");
    expect((await storedFile(request, project.id)).equals(original)).toBe(true);
  });
}
