import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import type { EvidenceDossier, EvidenceWorkspace, Project } from "../src/api/types";
import { openTab, readJson, REPO, storedFile } from "./helpers";

for (const [name, example] of [["vc", "nz_deeptech_vc"], ["supplier", "supplier_qualification"]] as const) {
  test(`${name} evidence review previews, confirms, exports and reopens history without editing project bytes`, async ({ page, request }, testInfo) => {
    const project = readJson(resolve(REPO, `examples/${example}/project.json`)) as Project;
    project.id = `evidence-workspace-${name}`;
    const imported = await request.post("/api/projects/import", { data: project });
    expect(imported.status()).toBe(201);
    const { fingerprint } = await imported.json() as { fingerprint: string };
    const dossier = readJson(resolve(REPO, `examples/evidence_demo/${name}.json`)) as EvidenceDossier;
    dossier.project_fingerprint = fingerprint;
    const first = dossier.claims[0], second = dossier.claims[1];
    if (!first || !second) throw Error("Demo claims missing");
    first.review = null;
    first.source.classification = "self_reported";
    second.origin = { kind: "tool", proposed_by: "Example analyst", tool_id: "synthetic-extractor", tool_version: "1" };
    const before = await storedFile(request, project.id);
    await page.goto(`/#/p/${project.id}`);
    await openTab(page, "Evidence");
    const panel = page.getByRole("region", { name: "Evidence Workspace", exact: true });
    await panel.getByLabel("Evidence dossier or review workspace").setInputFiles({ name: "dossier.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(dossier)) });
    await expect(panel.getByLabel("Evidence claims")).toContainText("synthetic-extractor 1");
    await expect(panel.getByLabel("Evidence claims")).toContainText("self_reported");
    await expect(panel.getByLabel("Measurement support")).toContainText("unsupported");
    await panel.getByRole("button", { name: "Review unreviewed_example", exact: true }).click();
    await panel.getByLabel("Reviewer", { exact: true }).fill("Fresh session analyst");
    await panel.getByLabel("Review decision", { exact: true }).selectOption("rejected");
    await panel.getByLabel("Review note").fill("Synthetic claim rejected after source check");
    await panel.getByRole("button", { name: "Preview review", exact: true }).click();
    await expect(panel.getByLabel("Proposed review", { exact: true })).toContainText("rejected");
    await expect(panel.getByText("Review history (0 appended)", { exact: true })).toBeVisible();
    await panel.getByRole("button", { name: "Confirm review in workspace" }).click();
    await expect(panel.getByText("Review history (1 appended)", { exact: true })).toBeVisible();
    await panel.getByRole("button", { name: "Review reviewed_example", exact: true }).click();
    await panel.getByLabel("Review decision", { exact: true }).selectOption("accepted");
    await panel.getByRole("button", { name: "Preview review", exact: true }).click();
    await expect(panel.getByLabel("Proposed review", { exact: true })).toContainText(String(first.value));
    await panel.getByRole("button", { name: "Confirm review in workspace" }).click();
    await expect(panel.getByText("Review history (2 appended)", { exact: true })).toBeVisible();
    await panel.getByLabel("Evidence claims").screenshot({ path: testInfo.outputPath("reviewed-claims.png") });
    await openTab(page, "Open Questions");
    await expect(page.getByText("Using the reviewed dossier from Evidence Workspace.")).toBeVisible();
    await expect(page.getByText(/What supports .*measurement for/).first()).toBeVisible();
    await openTab(page, "Evidence");
    const downloadEvent = page.waitForEvent("download");
    await panel.getByRole("button", { name: "Export review workspace", exact: true }).click();
    const download = await downloadEvent;
    const path = await download.path();
    if (!path) throw Error("Workspace download missing");
    const exported = JSON.parse(readFileSync(path, "utf8")) as EvidenceWorkspace;
    expect(exported.original_dossier).toEqual(dossier);
    expect(exported.reviews.map(r => r.review.status)).toEqual(["rejected", "accepted"]);
    expect(exported.source_project).toEqual((await request.get(`/api/projects/${project.id}`).then(r => r.json()) as { project: Project }).project);
    await page.reload();
    await openTab(page, "Evidence");
    await panel.getByLabel("Evidence dossier or review workspace").setInputFiles(path);
    await expect(panel.getByText("Review history (2 appended)", { exact: true })).toBeVisible();
    await expect(panel.getByLabel("Evidence claims")).toContainText("reviewed_example · accepted");
    await expect(panel.getByLabel("Evidence claims")).toContainText("unreviewed_example · rejected · outdated");
    expect((await storedFile(request, project.id)).equals(before)).toBe(true);
    await expect(page.getByRole("button", { name: "Undo", exact: true })).toBeDisabled();
  });
}

test("stale dossiers block review after a project edit and recover on undo", async ({ page, request }) => {
  const project = readJson(resolve(REPO, "examples/supplier_qualification/project.json")) as Project;
  project.id = "evidence-workspace-stale";
  const imported = await request.post("/api/projects/import", { data: project });
  const { fingerprint } = await imported.json() as { fingerprint: string };
  const dossier = readJson(resolve(REPO, "examples/evidence_demo/supplier.json")) as EvidenceDossier;
  dossier.project_fingerprint = fingerprint;
  await page.goto(`/#/p/${project.id}`); await openTab(page, "Evidence");
  const panel = page.getByRole("region", { name: "Evidence Workspace", exact: true });
  await panel.getByLabel("Evidence dossier or review workspace").setInputFiles({ name: "dossier.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(dossier)) });
  await expect(panel.getByRole("button", { name: "Review unreviewed_example", exact: true })).toBeEnabled();
  await panel.getByRole("button", { name: "Review unreviewed_example", exact: true }).click();
  await panel.getByLabel("Reviewer", { exact: true }).fill("Conflict reviewer");
  await panel.getByRole("button", { name: "Preview review", exact: true }).click();
  await expect(panel.getByRole("alert")).toContainText("only one claim may be accepted for a cell");
  await expect(panel.getByRole("button", { name: "Confirm review in workspace" })).toHaveCount(0);
  await panel.getByLabel("Review decision", { exact: true }).selectOption("rejected");
  await panel.getByRole("button", { name: "Preview review", exact: true }).click();
  await panel.getByRole("button", { name: "Confirm review in workspace" }).click();
  await expect(panel.getByText("Review history (1 appended)", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "← Projects", exact: true }).click();
  const leave = page.getByRole("dialog", { name: "Unsaved changes" });
  await expect(leave).toBeVisible();
  await leave.getByRole("button", { name: "Save and leave", exact: true }).click();
  await expect(leave).toHaveCount(0);
  await expect(panel.getByText(/Reviews have not been exported/)).toBeVisible();
  const download = page.waitForEvent("download");
  await panel.getByRole("button", { name: "Export review workspace", exact: true }).click();
  expect(await (await download).path()).not.toBeNull();
  await openTab(page, "Project");
  await page.getByLabel("Project title", { exact: true }).fill("Changed evidence context");
  await page.getByLabel("Project title", { exact: true }).press("Enter");
  await openTab(page, "Evidence");
  await expect(panel.getByRole("alert")).toContainText("EVIDENCE_STALE_PROJECT");
  await expect(panel.getByRole("button", { name: "Review unreviewed_example", exact: true })).toBeDisabled();
  await expect(panel.getByRole("button", { name: "Export review workspace", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(panel.getByRole("button", { name: "Review unreviewed_example", exact: true })).toBeEnabled();
});
