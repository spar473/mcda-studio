import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { openTab, readJson, REPO, storedFile } from "./helpers";
import type { DerivedPreview, FactorRunRecord, Project } from "../src/api/types";

test("review factor uncertainty, run and reopen a decision snapshot without changing project bytes", async ({ page, request }, testInfo) => {
  const project = readJson(resolve(REPO, "examples/derived_measurements/supplier-project.json")) as Project;
  const model = readJson(resolve(REPO, "examples/derived_measurements/supplier-model.json")) as DerivedPreview["model"];
  project.id = "factor-shared-supplier";
  const imported = await request.post("/api/projects/import", { data: project });
  expect(imported.status()).toBe(201);
  model.project_fingerprint = (await imported.json() as { fingerprint: string }).fingerprint;
  const before = await storedFile(request, project.id);
  await page.goto(`/#/p/${project.id}`);
  await openTab(page, "Measurements");
  await page.getByText("Calculated measurements", { exact: true }).click();
  const panel = page.getByLabel("Calculated measurements preview", { exact: true });
  await panel.getByLabel("Calculation model", { exact: true }).setInputFiles({ name: "model.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(model)) });
  const uncertainty = panel.getByLabel("Fundamental-factor uncertainty", { exact: true });
  await uncertainty.locator("summary").first().click();
  await uncertainty.getByRole("button", { name: "Start factor uncertainty sidecar" }).click();
  await uncertainty.getByLabel("Distribution reviewer", { exact: true }).fill("Reviewer");
  await uncertainty.getByRole("combobox", { name: "Source factor", exact: true }).selectOption("annual_units");
  await uncertainty.getByLabel("Lower bound", { exact: true }).fill("900");
  await uncertainty.getByLabel("Upper bound", { exact: true }).fill("1100");
  await uncertainty.getByRole("button", { name: "Set pending distribution" }).click();
  await expect(uncertainty.getByRole("button", { name: "Run factor uncertainty" })).toBeDisabled();
  await uncertainty.getByLabel("I accept these distributions and dependence assumptions").check();
  await uncertainty.getByLabel("Draw count", { exact: true }).fill("24");
  await uncertainty.getByLabel("Include a decision snapshot with this run").check();
  await uncertainty.getByLabel("Factor decision owner", { exact: true }).fill("Owner");
  await uncertainty.getByLabel("Factor decision rationale", { exact: true }).fill("Review the shared volume assumption before choosing.");
  await uncertainty.getByRole("button", { name: "Run factor uncertainty" }).click();
  const completed = uncertainty.getByRole("region", { name: "Completed factor run" });
  await expect(completed).toContainText("SMAA-2 with fundamental factors: sampled, 24 draws, seed 7");
  await expect(completed.getByLabel("Derived input questions")).toContainText("annual_units");
  await expect(completed).toContainText("Decision snapshot: Owner, deferred");
  await completed.getByRole("table", { name: "Factor acceptabilities" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("factor-uncertainty.png") });
  const event = page.waitForEvent("download");
  await completed.getByRole("button", { name: "Export factor run record" }).click();
  const path = await (await event).path();
  if (!path) throw Error("run download missing");
  const record = JSON.parse(readFileSync(path, "utf8")) as FactorRunRecord;
  expect(record.result.draw_count).toBe(24);
  expect(record.result.trace).toHaveLength(16);
  const replay = await request.post("/api/factor-uncertainty/verify", { data: { record, replay: true } });
  expect(replay.status()).toBe(200);
  expect(await replay.json()).toEqual(record);
  expect((await storedFile(request, project.id)).equals(before)).toBe(true);
  await uncertainty.getByLabel("Open factor run record", { exact: true }).setInputFiles(path);
  await expect(completed).toContainText("Verified historical snapshot. Its source matches the open project.");
  expect((await storedFile(request, project.id)).equals(before)).toBe(true);
  await openTab(page, "Open Questions");
  await page.getByLabel("Factor run record (optional)").setInputFiles(path);
  await expect(page.getByRole("region", { name: "Open Questions" })).toContainText("Are assumptions for factor annual_units");
});
