import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import type { ModelComparisonCompilation, StarterMaterialization, Project, ProjectDocument, AnyAnalysisRecord, ModelComparisonInspection } from "../src/api/types";
import { openTab, readJson, REPO, storedFile } from "./helpers";

for (const title of ["Blank", "Supplier selection", "Infrastructure procurement", "Venture screening"]) {
  test(`${title} gallery: fresh review reset, portable lineage and intact worked example`, async ({ page, request }) => {
    await page.goto("/");
    await page.getByRole("button", { name: "New project…", exact: true }).click();
    const gallery=page.getByRole("region",{name:"Starter gallery"});
    await gallery.getByRole("button",{name:`Create my project — ${title}`,exact:true}).click();
    const lineage=gallery.getByRole("region",{name:"Starter lineage"});
    await expect(lineage).toContainText("Fresh unreviewed project");
    await expect(lineage.getByRole("button",{name:"Save and open prepared project"})).toBeDisabled();
    const download=page.waitForEvent("download");
    await lineage.getByRole("button",{name:"Download materials and lineage",exact:true}).click();
    const file=await (await download).path();if(!file)throw Error("Missing materials download");
    const fresh=JSON.parse(readFileSync(file,"utf8")) as StarterMaterialization;
    expect(fresh.receipt.request.mode).toBe("fresh");
    expect(fresh.receipt.cleared_fields).toContain("project/decision_maker");
    expect(Object.values(fresh.artifacts).every(item=>item.kind!=="model_output_run")).toBe(true);
    const keyed=await request.post("/api/starter-templates/instantiate",{data:fresh.receipt.request});
    expect(keyed.status()).toBe(200);expect(await keyed.json()).toEqual(fresh);
    await lineage.getByRole("button",{name:"Save and open prepared project"}).click();
    await expect(page.getByRole("heading",{level:1,name:fresh.project.title,exact:true})).toBeVisible();
    await expect(page.getByText(/Carried human acceptances and saved runs were cleared/)).toBeVisible();
    const saved=await request.get(`/api/projects/${fresh.project.id}`);
    expect((await saved.json() as ProjectDocument).fingerprint).toBe(fresh.receipt.project_fingerprint);
    await page.getByRole("button",{name:"← Projects",exact:true}).click();
    await page.getByRole("button",{name:"New project…",exact:true}).click();
    await gallery.getByLabel("Reopen starter materials and lineage").setInputFiles(file);
    await expect(lineage).toContainText(fresh.receipt.project_fingerprint);
    await gallery.getByRole("button",{name:`Open worked example — ${title}`,exact:true}).click();
    await expect(lineage).toContainText("Intact worked example");
    const workedDownload=page.waitForEvent("download");
    await lineage.getByRole("button",{name:"Download materials and lineage",exact:true}).click();
    const workedFile=await (await workedDownload).path();if(!workedFile)throw Error("Missing worked download");
    const worked=JSON.parse(readFileSync(workedFile,"utf8")) as StarterMaterialization;
    expect(worked.receipt.project_fingerprint).toBe(worked.receipt.original_project_fingerprint);
    expect(worked.receipt.cleared_fields).toEqual([]);
    expect(worked.project.id).not.toBe(fresh.project.id);
    await lineage.getByRole("button",{name:"Save and open prepared project"}).click();
    await expect(page.getByRole("heading",{level:1,name:worked.project.title,exact:true})).toBeVisible();
    const intact=await request.get(`/api/projects/${worked.project.id}`);
    expect((await intact.json() as ProjectDocument).fingerprint).toBe(worked.receipt.project_fingerprint);
    if(worked.project.alternatives.length){
      await openTab(page,"Results");
      await expect(page.getByRole("table",{name:"Ranking",exact:true})).toBeVisible();
      const analysisDownload=page.waitForEvent("download");
      await page.getByRole("button",{name:"Download analysis JSON",exact:true}).click();
      const analysisFile=await (await analysisDownload).path();if(!analysisFile)throw Error("Missing analysis download");
      const analysis=JSON.parse(readFileSync(analysisFile,"utf8")) as {record:AnyAnalysisRecord};
      const evaluated=await request.post("/api/evaluate",{data:{project:worked.project,configuration:worked.project.analysis}});
      expect(evaluated.status()).toBe(200);expect(await evaluated.json()).toEqual(analysis.record.result);
    }
  });
}

test("model comparison: overlap, exact selection diff, historical export, open question and stale refusal",async({page,request},testInfo)=>{
  const base=resolve(REPO,"examples/starter_templates/venture_screening");
  const project=readJson(resolve(base,"project.json")) as Project;
  const imported=await request.post("/api/projects/import",{data:project});expect([201,409]).toContain(imported.status());
  const original=await storedFile(request,project.id);
  await page.goto(`/#/p/${project.id}`);await openTab(page,"Measurements");
  await page.getByText("Calculated measurements",{exact:true}).click();
  const panel=page.getByRole("region",{name:"Model comparisons",exact:true});
  await panel.getByLabel("Model comparison or historical bundle").setInputFiles(resolve(base,"model_comparison.json"));
  await expect(panel.getByText("Which assumptions explain these model estimates?",{exact:true})).toBeVisible();
  await expect(panel.getByText("support_enclosure",{exact:true})).toBeVisible();
  await expect(panel.getByText("source_interval",{exact:true})).toBeVisible();
  await expect(panel.getByRole("combobox",{name:"Selected model output",exact:true})).toHaveValue("");
  await panel.getByLabel("Model reviewer",{exact:true}).fill("Illustrative reviewer");
  await panel.getByLabel("Model review rationale").fill("Reviewed the invented scope and selected the separate comparison model");
  await panel.getByRole("combobox",{name:"Selected model output",exact:true}).selectOption("right");
  await panel.getByRole("combobox",{name:"Target alternative",exact:true}).selectOption("a");
  await panel.getByRole("combobox",{name:"Target criterion",exact:true}).selectOption("annual");
  await expect(panel.getByLabel("Model selection measurement diff")).toContainText("600000 → selected output: 1000000");
  await panel.getByLabel(/I reviewed this exact population/).check();
  await panel.getByLabel(/I reviewed both declarations/).check();
  await panel.getByRole("button",{name:"Compile selected output into a separate copy"}).click();
  const result=panel.getByRole("region",{name:"Model selection result"});await expect(result).toBeVisible();
  const downloaded=page.waitForEvent("download");await result.getByRole("button",{name:"Download model comparison bundle",exact:true}).click();
  const file=await (await downloaded).path();if(!file)throw Error("Missing comparison bundle");
  const bundle=JSON.parse(readFileSync(file,"utf8")) as ModelComparisonCompilation;
  expect(bundle.calculation.project.performances.find(p=>p.alternative_id==="a"&&p.criterion_id==="annual")?.value).toBe(1000000);
  expect((await storedFile(request,project.id)).equals(original)).toBe(true);
  const verified=await request.post("/api/model-comparisons/verify",{data:{document:bundle}});expect(verified.status()).toBe(200);expect(await verified.json()).toEqual(bundle);
  await page.screenshot({path:testInfo.outputPath("model-comparison.png")});
  await openTab(page,"Open Questions");
  await expect(page.getByRole("region",{name:"Open Questions",exact:true})).toContainText("Which assumptions explain these model estimates?");
  await openTab(page,"Measurements");
  await panel.getByRole("combobox",{name:"Displayed input to review",exact:true}).selectOption("right:source:total");
  const reviewed=page.waitForResponse(response=>response.url().endsWith("/api/model-comparisons/review-input"));
  await panel.getByRole("button",{name:"Record one input review",exact:true}).click();
  const revised=await (await reviewed).json() as ModelComparisonInspection;
  await expect(result).not.toBeVisible();
  await expect(panel.getByRole("button",{name:"Compile selected output into a separate copy"})).toBeDisabled();
  const stale=await request.post("/api/model-comparisons/compile",{data:{project,comparison:revised.comparison,selection:bundle.selection,expected_review_digest:bundle.inspection.review_digest}});
  expect(stale.status()).toBe(412);expect((await stale.json() as {error:{code:string}}).error.code).toBe("STALE_REVISION");
  expect((await storedFile(request,project.id)).equals(original)).toBe(true);
});
