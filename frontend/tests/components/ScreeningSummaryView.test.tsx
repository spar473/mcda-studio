import { act, fireEvent, render, renderHook, screen, within } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { api } from "../../src/api/client";
import type { Project, ScreeningSummary } from "../../src/api/types";
import { ScreeningSummarySection } from "../../src/components/ResultsPanel";
import { ScreeningSummaryView } from "../../src/components/results/ScreeningSummaryView";
import { BASE_SELECTION, resolveContext } from "../../src/state/analysisContext";
import { useScreeningSummary } from "../../src/state/useScreeningSummary";
import projectJSON from "../fixtures/screening-study-project.json";
import summaryJSON from "../fixtures/screening-summary.json";

// Engine output for the venture study under the Commercial/traction-led profile (generated by
// scripts/export_model_test_fixtures.py): every number below is Python's, only laid out here.
const project = projectJSON as unknown as Project;
const summary = summaryJSON as unknown as ScreeningSummary;
const rows = () => within(screen.getByRole("table", { name: "Screening summary" })).getAllByRole("row").slice(1);
const cells = (name: string) => {
  const row = rows().find((r) => within(r).queryByRole("rowheader", { name }));
  if (!row) throw new Error(`no row ${name}`);
  return within(row).getAllByRole("cell").map((c) => c.textContent);
};

describe("the screening summary table", () => {
  it("lays out the engine's rows in its order with every column", () => {
    render(<ScreeningSummaryView summary={summary} project={project}/>);
    expect(rows().map((r) => within(r).getByRole("rowheader").textContent)).toEqual(summary.rows.map((r) => r.name));
    const headers = screen.getAllByRole("columnheader").map((h) => h.textContent);
    expect(headers).toEqual(["Rank", "Alternative", "Overall value", "Class (margin)", "Requirements", "Largest contributions", "Closest change", "Open questions"]);
    expect(cells("Hectre")).toEqual([
      "2", "0.5991", "Monitor (0.0009)", "Meets all",
      "Commercial stage 0.1008; Customer validation 0.0907",
      "−0.0010 of total weight on Strategic partnerships and channels → moves to Prioritise for diligence", "22",
    ]);
    expect(cells("Hnry")[3]).toBe("Fails: Stage at most Series A");
    expect(cells("Upstock")[5]).toBe("+0.4140 of total weight on Market → swaps with Wych");
    fireEvent.click(screen.getByRole("button", { name: "About: Preference values under this profile; not probabilities or predictions." }));
    expect(screen.getByText(/not a probability or a prediction/)).toBeInTheDocument();
    expect(screen.getByRole("columnheader", { name: "Closest change" })).toHaveAttribute("title", summary.fragility_definition);
  });

  it("shows an unavailable summary's reason and no table, never zeros", () => {
    const unavailable: ScreeningSummary = { ...summary, status: "unavailable", reason: "Ranking unavailable: 1 measurement(s) are missing.", rows: [], columns: [] };
    render(<ScreeningSummaryView summary={unavailable} project={project}/>);
    expect(screen.getByRole("status")).toHaveTextContent("Ranking unavailable: 1 measurement(s) are missing.");
    expect(screen.queryByRole("table")).not.toBeInTheDocument();
  });

  it("drops an absent column and says why", () => {
    const noClasses: ScreeningSummary = { ...summary, columns: summary.columns.map((c) => c.column === "classes" ? { ...c, available: false, reason: "No classes are set up." } : c) };
    render(<ScreeningSummaryView summary={noClasses} project={project}/>);
    expect(screen.queryByRole("columnheader", { name: "Class (margin)" })).not.toBeInTheDocument();
    expect(screen.getByLabelText("Summary columns not shown")).toHaveTextContent("Not shown: Class (No classes are set up.)");
  });

  it("reads a tie and a model without any one-way change in plain words", () => {
    const [first, second] = summary.rows;
    if (!first || !second) throw new Error("fixture rows");
    const empty = { kind: null, criterion_id: null, criterion_name: null, direction: null, base_local_weight: null,
      local_weight: null, weight_change: null, other_alternative_id: null, class_after_id: null };
    const changed: ScreeningSummary = { ...summary, rows: [
      { ...first, fragility: { ...empty, status: "tied", tied_with: [second.alternative_id] } },
      { ...second, fragility: { ...empty, status: "none", tied_with: [] } },
    ] };
    render(<ScreeningSummaryView summary={changed} project={project}/>);
    expect(cells(first.name)[5]).toBe(`Tied now with ${second.name}`);
    expect(cells(second.name)[5]).toBe("No one-way change in range");
  });

  it("is collapsed and labelled as MAVT's reading under another method", () => {
    render(<ScreeningSummarySection project={project} request={{ status: "ready", result: summary }} collapsed/>);
    expect(screen.getByText("MAVT screening summary").closest("details")).not.toHaveAttribute("open");
  });
});

describe("the screening summary request", () => {
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers(); });
  const context = (fingerprint: string, profileId: string | null = "commercial_traction") =>
    resolveContext(project, fingerprint, { ...BASE_SELECTION, profileId });
  const start = () => act(async () => { await vi.advanceTimersByTimeAsync(121); });

  it("accepts only a response for the selected revision, profile and scenario", async () => {
    const matching = { ...summary, project_fingerprint: "rev", configuration: context("rev").configuration };
    vi.spyOn(api, "screeningSummary").mockResolvedValue(matching);
    const { result } = renderHook(() => useScreeningSummary(project, context("rev")));
    await start();
    expect(result.current).toMatchObject({ status: "ready" });
  });

  it("refuses a response for another profile, even with the same revision", async () => {
    const other = { ...summary, project_fingerprint: "rev", configuration: context("rev").configuration, weight_profile_id: "technical_ip" };
    vi.spyOn(api, "screeningSummary").mockResolvedValue(other);
    const { result } = renderHook(() => useScreeningSummary(project, context("rev")));
    await start();
    expect(result.current).toMatchObject({ status: "error", message: "Screening summary does not match the selected revision and configuration." });
  });

  it("hides a ready summary immediately when the profile changes", async () => {
    const technical = context("rev", "technical_ip");
    vi.spyOn(api, "screeningSummary").mockResolvedValue({ ...summary, project_fingerprint: "rev", configuration: technical.configuration, weight_profile_id: "technical_ip" });
    const { result, rerender } = renderHook(({ ctx }) => useScreeningSummary(project, ctx), { initialProps: { ctx: technical } });
    await start(); expect(result.current.status).toBe("ready");
    rerender({ ctx: context("rev") });
    expect(result.current).toEqual({ status: "loading" });
  });
});
